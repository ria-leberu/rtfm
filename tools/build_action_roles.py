"""Build action intent from the pinned mob SQL and local spell resources."""
import argparse
import json
import re
from pathlib import Path
from build_catalogue import read_sql

parser = argparse.ArgumentParser()
parser.add_argument('--source', type=Path, required=True)
parser.add_argument('--spells', type=Path, required=True)
args = parser.parse_args()
lines = ['-- Generated by tools/build_action_roles.py from mob targets and spell skill/targets.',
         'return { moves = {']
for row in read_sql(args.source / 'sql/mob_skills.sql', 'mob_skills'):
    targets = row['mob_valid_targets']
    if not isinstance(targets, int) or targets == 0:
        continue
    role = 'offensive' if targets & 4 else 'defensive'
    lines.append(f"[{row['mob_skill_id']}]='{role}',")
lines.append('}, spells = {')
roles = {}
for line in args.spells.read_text(encoding='utf-8-sig').splitlines():
    name = re.search(r'\ben="([^"]+)"', line)
    skill = re.search(r'\bskill=(\d+)', line)
    targets = re.search(r'\btargets=(\d+)', line)
    if not (name and skill and targets):
        continue
    skill, targets = int(skill[1]), int(targets[1])
    if not targets:
        continue
    role = 'defensive' if skill in (33, 34) or not targets & 32 else 'offensive'
    roles[name[1].lower()] = role
for name, role in sorted(roles.items()):
    lines.append(f'[{json.dumps(name)}]="{role}",')
lines.append('} }')
Path('data/generated/action_roles.lua').write_text('\n'.join(lines) + '\n', encoding='utf-8')
