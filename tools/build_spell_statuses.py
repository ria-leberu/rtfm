"""Extract harmful spell status metadata from local spell resources, offline."""
import argparse
import hashlib
import json
import re
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('--spells', type=Path, required=True)
args = parser.parse_args()
effects = {}
damage = {}
cast_times = {}
elements = ['fire', 'ice', 'wind', 'earth', 'lightning', 'water', 'light', 'dark']
for line in args.spells.read_text(encoding='utf-8-sig').splitlines():
    name = re.search(r'\ben="([^"]+)"', line)
    cast_time = re.search(r'\bcast_time=([\d.]+)', line)
    if name and cast_time:
        key, value = name[1].lower(), float(cast_time[1])
        if key not in cast_times or cast_times[key] == value:
            cast_times[key] = value
        else:
            # Duplicate-name spells with different timings require a packet ID.
            cast_times[key] = None
    status = re.search(r'\bstatus=(\d+)', line)
    targets = re.search(r'\btargets=(\d+)', line)
    skill = re.search(r'\bskill=(\d+)', line)
    element = re.search(r'\belement=(\d+)', line)
    if name and skill and targets and element and int(targets[1]) & 32:
        # Element metadata alone does not imply damage (Blind is dark, for example).
        key = name[1].lower()
        direct = int(skill[1]) == 36 and not status
        known_damage = re.match(r'^(?:bio|dia|diaga|banish|banishga|holy|drain|comet|meteor|kaustra)(?: |$)', key)
        if (direct or known_damage) and int(element[1]) < len(elements):
            damage[key] = elements[int(element[1])]
    if name and status and targets and int(targets[1]) & 32 and int(status[1]) > 0:
        if skill and int(skill[1]) in (33, 34):
            continue
        effects.setdefault(name[1].lower(), set()).add(int(status[1]))
lines = ['-- Generated by tools/build_spell_statuses.py from local metrics/resources/spells.lua.',
         '-- Source SHA256: ' + hashlib.sha256(args.spells.read_bytes()).hexdigest(), 'return {']
for name, statuses in sorted(effects.items()):
    lines.append('[' + json.dumps(name) + ']={' + ','.join(map(str, sorted(statuses))) + '},')
lines.append('}')
Path('data/generated/spell_statuses.lua').write_text('\n'.join(lines) + '\n', encoding='utf-8')
lines = ['-- Generated by tools/build_spell_statuses.py; damaging spell elements only.', 'return {']
for name, element in sorted(damage.items()):
    lines.append('[' + json.dumps(name) + ']=' + json.dumps(element) + ',')
lines.append('}')
Path('data/generated/spell_damage.lua').write_text('\n'.join(lines) + '\n', encoding='utf-8')
lines = ['-- Generated by tools/build_spell_statuses.py; base cast times in seconds.', 'return {']
for name, duration in sorted(cast_times.items()):
    if duration is not None:
        lines.append('[' + json.dumps(name) + ']=' + str(duration) + ',')
lines.append('}')
Path('data/generated/spell_cast_times.lua').write_text('\n'.join(lines) + '\n', encoding='utf-8')
